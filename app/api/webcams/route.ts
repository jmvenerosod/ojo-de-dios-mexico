// Caché en memoria de IDs auto-reparados cuando una transmisión en vivo de YouTube cambia de ID
const healedVideoCache = new Map<string, string>();

async function isYouTubePlayable(videoId: string): Promise<boolean> {
  try {
    const res = await fetch(`https://www.youtube.com/watch?v=${videoId}`, {
      headers: {
        'User-Agent':
          'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36',
        'Accept-Language': 'es-MX,es;q=0.9',
      },
      signal: AbortSignal.timeout(4000),
      cache: 'no-store',
    });
    if (!res.ok) return false;
    const html = await res.text();
    const statusMatch = html.match(/"playabilityStatus":\{"status":"([^"]+)"/);
    const status = statusMatch?.[1] || 'UNKNOWN';
    const isEmbeddable = !html.includes('"playableInEmbed":false');
    const isOfflineRecording =
      html.includes('La grabación de esta transmisión en vivo no está disponible') ||
      html.includes('This live stream recording is not available') ||
      html.includes('LIVE_STREAM_OFFLINE');
    return status === 'OK' && isEmbeddable && !isOfflineRecording;
  } catch {
    return true; // En caso de timeout de red, conservar ID verificado
  }
}

async function healCameraStream(cam: CameraConfig, excludeId?: string): Promise<string> {
  const queries = [
    `${cam.searchQuery} en vivo`,
    `${cam.city} ${cam.state} mexico en vivo webcam`,
    `${cam.city} ${cam.state} mexico 4k`,
  ];

  for (const q of queries) {
    try {
      const res = await fetch(
        `https://www.youtube.com/results?search_query=${encodeURIComponent(q)}`,
        {
          headers: {
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36',
            'Accept-Language': 'es-MX,es;q=0.9',
          },
          signal: AbortSignal.timeout(4500),
          cache: 'no-store',
        }
      );
      if (!res.ok) continue;
      const html = await res.text();
      const candidateIds = [
        ...new Set([...html.matchAll(/"videoId":"([a-zA-Z0-9_-]{11})"/g)].map((m) => m[1])),
      ].slice(0, 6);

      for (const candidate of candidateIds) {
        if (candidate === excludeId) continue;
        const ok = await isYouTubePlayable(candidate);
        if (ok) {
          healedVideoCache.set(cam.id, candidate);
          return candidate;
        }
      }
    } catch {
      // Continuar con siguiente consulta
    }
  }
  return cam.verifiedVideoId;
}

export async function GET(request: Request) {
  const { searchParams } = new URL(request.url);
  const healId = searchParams.get('healId');
  const excludeVideoId = searchParams.get('exclude') || undefined;

  if (healId) {
    const targetCam = MEXICO_CAMERAS.find((c) => c.id === healId);
    if (targetCam) {
      const newVideoId = await healCameraStream(
        targetCam,
        excludeVideoId || healedVideoCache.get(healId) || targetCam.verifiedVideoId
      );
      return NextResponse.json({
        id: targetCam.id,
        videoId: newVideoId,
        embedUrl: `https://www.youtube.com/embed/${newVideoId}?autoplay=1&mute=1&controls=1&rel=0&modestbranding=1`,
      });
    }
  }

  const cameras = MEXICO_CAMERAS.map((cam) => {
    const activeVideoId = healedVideoCache.get(cam.id) || cam.verifiedVideoId;
    return {
      ...cam,
      videoId: activeVideoId,
      embedUrl: `https://www.youtube.com/embed/${activeVideoId}?autoplay=1&mute=1&controls=1&rel=0&modestbranding=1`,
    };
  });

  return NextResponse.json({
    cameras,
    total: cameras.length,
    updatedAt: new Date().toISOString(),
  });
}
